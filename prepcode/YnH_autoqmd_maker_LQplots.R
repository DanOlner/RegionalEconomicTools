  #   'sector = "',
  #   sector,
  #   '"\n\n',
  #   read_file('prepcode/makemap_ynhtext.R'),
  #   "\n\n\n"
  # )
  
  
  # End r block
  # document = paste0(
  #   document,
  #   "```\n\n\n"
  # )
  
  
}


write_file(document,'quarto_docs/yorkshire_n_humber_LQplotcollections_autogenerated.qmd')
