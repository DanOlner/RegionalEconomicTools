  #   "```{r, fig-",
  #   gsub('[[:punct:]]| ','',sector),#use sector name for fig, remove punct and spaces
  #   "_map}\n#| fig-width: 8\n#| fig-height: 9\n\n"
  # )
  
  # Map code
  # document = paste0(
